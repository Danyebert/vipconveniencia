-- Venda transacional: valida estoque, grava preços históricos, baixa estoque e atualiza caixa.
create or replace function public.finalizar_venda(
  p_cliente_id bigint,
  p_forma_pagamento_id bigint,
  p_itens jsonb
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item jsonb;
  v_produto public.produtos%rowtype;
  v_total numeric(14,2) := 0;
  v_venda_id bigint;
  v_qtd numeric(14,3);
  v_subtotal numeric(14,2);
  v_caixa_id bigint;
begin
  if jsonb_array_length(p_itens) = 0 then
    raise exception 'A venda precisa ter pelo menos um item.';
  end if;

  -- Primeiro bloqueia e valida todos os produtos.
  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    v_qtd := (v_item->>'quantidade')::numeric;
    if v_qtd <= 0 then raise exception 'Quantidade inválida.'; end if;

    select * into v_produto
      from public.produtos
      where id = (v_item->>'produto_id')::bigint and ativo = true
      for update;

    if not found then raise exception 'Produto não encontrado ou inativo.'; end if;
    if v_produto.estoque_atual < v_qtd then
      raise exception 'Estoque insuficiente para % (disponível: %).', v_produto.nome, v_produto.estoque_atual;
    end if;
    v_total := v_total + round(v_produto.preco_venda * v_qtd, 2);
  end loop;

  insert into public.vendas(cliente_id, subtotal, desconto, total, status)
  values (p_cliente_id, v_total, 0, v_total, 'finalizada')
  returning id into v_venda_id;

  for v_item in select * from jsonb_array_elements(p_itens)
  loop
    v_qtd := (v_item->>'quantidade')::numeric;
    select * into v_produto from public.produtos where id=(v_item->>'produto_id')::bigint for update;
    v_subtotal := round(v_produto.preco_venda * v_qtd, 2);

    insert into public.venda_itens(venda_id, produto_id, quantidade, preco_unitario, preco_custo, subtotal)
    values(v_venda_id, v_produto.id, v_qtd, v_produto.preco_venda, v_produto.preco_compra, v_subtotal);

    update public.produtos set estoque_atual = estoque_atual - v_qtd, updated_at=now() where id=v_produto.id;

    insert into public.movimentacoes_estoque(produto_id,tipo,quantidade,estoque_anterior,estoque_posterior,custo_unitario,venda_id,observacao)
    values(v_produto.id,'VENDA',-v_qtd,v_produto.estoque_atual,v_produto.estoque_atual-v_qtd,v_produto.preco_compra,v_venda_id,'Venda #'||v_venda_id);
  end loop;

  insert into public.venda_pagamentos(venda_id, forma_pagamento_id, valor)
  values(v_venda_id,p_forma_pagamento_id,v_total);

  select id into v_caixa_id from public.caixas where status='aberto' order by aberto_em desc limit 1;
  if v_caixa_id is not null then
    insert into public.movimentacoes_caixa(caixa_id,tipo,valor,venda_id,forma_pagamento_id,descricao)
    values(v_caixa_id,'VENDA',v_total,v_venda_id,p_forma_pagamento_id,'Venda #'||v_venda_id);
  end if;

  return jsonb_build_object('venda_id',v_venda_id,'total',v_total);
end;
$$;

