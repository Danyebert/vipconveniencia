create table if not exists public.categorias (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.produtos (
  id bigint generated by default as identity primary key,
  categoria_id bigint not null references public.categorias(id),
  nome text not null,
  descricao text,
  preco_compra numeric(14,2) not null default 0 check (preco_compra >= 0),
  margem numeric(8,2) not null default 0,
  preco_sugerido numeric(14,2) not null default 0,
  preco_venda numeric(14,2) not null default 0 check (preco_venda >= 0),
  estoque_atual numeric(14,3) not null default 0 check (estoque_atual >= 0),
  estoque_minimo numeric(14,3) not null default 0,
  imagem_url text,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_produtos_categoria on public.produtos(categoria_id);
create index if not exists idx_produtos_ativo on public.produtos(ativo);

create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  nome text not null,
  cpf text unique,
  telefone text,
  cep text,
  endereco text,
  numero text,
  bairro text,
  cidade text,
  uf text,
  created_at timestamptz not null default now()
);

create table if not exists public.formas_pagamento (
  id bigint generated by default as identity primary key,
  nome text not null unique,
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.vendas (
  id bigint generated by default as identity primary key,
  cliente_id bigint references public.clientes(id),
  subtotal numeric(14,2) not null default 0,
  desconto numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  status text not null default 'finalizada' check (status in ('finalizada','cancelada')),
  created_at timestamptz not null default now()
);
create index if not exists idx_vendas_created_at on public.vendas(created_at desc);

create table if not exists public.venda_itens (
  id bigint generated by default as identity primary key,
  venda_id bigint not null references public.vendas(id) on delete cascade,
  produto_id bigint not null references public.produtos(id),
  quantidade numeric(14,3) not null check (quantidade > 0),
  preco_unitario numeric(14,2) not null,
  preco_custo numeric(14,2) not null,
  subtotal numeric(14,2) not null
);

create table if not exists public.venda_pagamentos (
  id bigint generated by default as identity primary key,
  venda_id bigint not null references public.vendas(id) on delete cascade,
  forma_pagamento_id bigint not null references public.formas_pagamento(id),
  valor numeric(14,2) not null check (valor >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.movimentacoes_estoque (
  id bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos(id),
  tipo text not null check (tipo in ('ENTRADA','VENDA','AJUSTE','PERDA','CANCELAMENTO')),
  quantidade numeric(14,3) not null,
  estoque_anterior numeric(14,3) not null,
  estoque_posterior numeric(14,3) not null check (estoque_posterior >= 0),
  custo_unitario numeric(14,2),
  venda_id bigint references public.vendas(id),
  observacao text,
  created_at timestamptz not null default now()
);
create index if not exists idx_mov_estoque_produto on public.movimentacoes_estoque(produto_id, created_at desc);

create table if not exists public.caixas (
  id bigint generated by default as identity primary key,
  valor_inicial numeric(14,2) not null default 0,
  status text not null default 'aberto' check (status in ('aberto','fechado')),
  aberto_em timestamptz not null default now(),
  fechado_em timestamptz,
  valor_final_esperado numeric(14,2),
  valor_final_informado numeric(14,2),
  diferenca numeric(14,2)
);

create unique index if not exists apenas_um_caixa_aberto
  on public.caixas ((status)) where status = 'aberto';

create table if not exists public.movimentacoes_caixa (
  id bigint generated by default as identity primary key,
  caixa_id bigint not null references public.caixas(id),
  tipo text not null check (tipo in ('VENDA','SANGRIA','SUPRIMENTO')),
  valor numeric(14,2) not null check (valor >= 0),
  venda_id bigint references public.vendas(id),
  forma_pagamento_id bigint references public.formas_pagamento(id),
  descricao text,
  created_at timestamptz not null default now()
);

